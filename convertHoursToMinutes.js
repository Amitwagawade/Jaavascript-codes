// Write a function to convert hours into minutes.
// Instructions:
// Return the calculated minutes from given hours.
// Hint: Multiply hours with 60 to convert it to minutes.
// Example:
// For this input hours = 2, the result should be: 120
// Reason: 2 multiplied by 60 is 120.

function convertHoursToMinutes(hours) {
  return hours * 60;
}
