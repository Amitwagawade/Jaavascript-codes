// Write a function to check if a number is greater than five.
// Instructions:
// If the number is greater than 5, return "Yes". Otherwise, return "No".
// Example:
// For this input num = 7, the result should be: "Yes"
// Reason: 7 is greater than 5. So, the function returns "Yes".

function isGreaterThanFive(num) {
  if (num > 5) {
    return "Yes";
  } else {
    return "No";
  }
}
